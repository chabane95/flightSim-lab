"""Write an offline browser replay from a completed two-dimensional flight."""

import json
from pathlib import Path
from tempfile import NamedTemporaryFile

import numpy as np


def export_replay(destination: Path, flight, burnout: float, dt: float) -> None:
    t, _, z, _, _, _ = flight
    # The viewer interpolates between frames. Keep the exact solver samples
    # nearest the two events, plus the interpolated ground-contact sample.
    stride = max(1, round(0.05 / dt))
    indices = set(range(0, len(t), stride))
    indices.update((len(t) - 1, int(np.argmax(z)), int(np.argmin(abs(t - burnout)))))

    rows = []
    for index in sorted(indices):
        row = [round(float(t[index]), 9)]
        row.extend(round(float(column[index]), 6) for column in flight[1:])
        rows.append(json.dumps(row, separators=(",", ":"), allow_nan=False))

    cutoff = json.dumps(float(burnout), allow_nan=False)
    step = json.dumps(float(dt), allow_nan=False)
    samples = ",\n".join(rows)
    data = (
        "// Generated by python 2d_sim/main.py --export\n"
        f'window.FLIGHT_DATA = {{"burnout":{cutoff},"dt":{step},"samples":[\n{samples}\n]}};\n'
    ).encode("utf-8")
    if destination.is_file() and destination.read_bytes() == data:
        return

    destination.parent.mkdir(parents=True, exist_ok=True)
    temp = NamedTemporaryFile(dir=destination.parent, delete=False)
    temporary = Path(temp.name)
    try:
        with temp:
            temp.write(data)
        temporary.replace(destination)
    finally:
        temporary.unlink(missing_ok=True)
